#!/bin/bash
# Throwaway macOS VMs for testing Cairn (needs Tart: brew install openai/tools/tart).
#
#   scripts/vm.sh base      one-time: build the clean "cairn-base" VM from Apple's latest IPSW
#   scripts/vm.sh fresh     throw away "cairn-test" and clone a clean one from cairn-base
#   scripts/vm.sh stage     build Cairn.app and scan this Mac into the shared folder (read-only)
#   scripts/vm.sh run       boot cairn-test with the shared folder attached
#   scripts/vm.sh compare   diff this Mac's manifest against the VM's
#
# Inside the VM, open Finder > My Shared Files > cairn and double-click a
# .command file: "Run Cairn scan" (writes vm.yaml), "Restore preview", "Restore apply".
#
# The shared folder lives outside the repo (~/CairnVM/share) because it holds a
# real scan of this Mac, which must never be committed.
set -euo pipefail

cd "$(dirname "$0")/.."
ROOT="$(pwd)"
BASE="cairn-base"
TEST="cairn-test"
SHARE="${CAIRN_VM_SHARE:-$HOME/CairnVM/share}"
CPUS="${CAIRN_VM_CPUS:-4}"
MEMORY_MB="${CAIRN_VM_MEMORY_MB:-6144}"
DISK_GB="${CAIRN_VM_DISK_GB:-60}"

need_tart() {
    command -v tart >/dev/null || { echo "Tart isn't installed: brew install openai/tools/tart" >&2; exit 1; }
}
vm_exists() { tart list --quiet 2>/dev/null | grep -qx "$1"; }

case "${1:-}" in
base)
    need_tart
    if vm_exists "$BASE"; then echo "$BASE already exists."; exit 0; fi
    IPSW_DONE="$(ls "$HOME"/CairnVM/ipsw/*_"$(sw_vers -buildVersion)"_Restore.ipsw 2>/dev/null | head -1 || true)"
    if [ -n "$IPSW_DONE" ]; then
        echo "==> Using downloaded $(basename "$IPSW_DONE")"
        tart create "$BASE" --from-ipsw "$IPSW_DONE" --disk-size "$DISK_GB"
        tart set "$BASE" --cpu "$CPUS" --memory "$MEMORY_MB"
        echo "Next: tart run $BASE, finish Setup Assistant, shut down."
        exit 0
    fi
    # Download the IPSW ourselves: curl resumes after a dropped connection,
    # whereas `tart create --from-ipsw latest` throws away a partial download.
    # Use the build this Mac runs, so the VM matches the host.
    BUILD="$(sw_vers -buildVersion)"
    URL="$(curl -fsS https://mesu.apple.com/assets/macos/com_apple_macOSIPSW/com_apple_macOSIPSW.xml \
        | grep -oE "https://[^<]*_${BUILD}_Restore\.ipsw" | head -1)"
    [ -n "$URL" ] || { echo "Apple's catalog has no IPSW for build $BUILD." >&2; exit 1; }
    IPSW="$HOME/CairnVM/ipsw/$(basename "$URL")"
    mkdir -p "$(dirname "$IPSW")"
    echo "==> Downloading $(basename "$URL") (resumable; rerun to continue)"
    until curl -fL -C - --retry 10 --retry-all-errors --progress-bar -o "$IPSW.part" "$URL"; do
        echo "Download interrupted, resuming in 10 s…" >&2; sleep 10
    done
    mv "$IPSW.part" "$IPSW"
    echo "==> Creating $BASE (installs macOS into the VM; takes a while)"
    tart create "$BASE" --from-ipsw "$IPSW" --disk-size "$DISK_GB"
    tart set "$BASE" --cpu "$CPUS" --memory "$MEMORY_MB"
    cat <<EOF

Next, finish Setup Assistant once by hand:
  tart run $BASE
Create a local user, skip Apple Account sign-in for now, then shut the VM down.
Every test clones this clean state, so don't install anything in it.
EOF
    ;;
fresh)
    need_tart
    vm_exists "$BASE" || { echo "No $BASE yet. Run: scripts/vm.sh base" >&2; exit 1; }
    if vm_exists "$TEST"; then tart stop "$TEST" 2>/dev/null || true; tart delete "$TEST"; fi
    tart clone "$BASE" "$TEST"
    echo "Clean $TEST ready."
    ;;
stage)
    mkdir -p "$SHARE"
    scripts/build-app.sh
    # The VM's shared-folder mount caches files by path, so a rebuilt app at the
    # same path can still run the old binary. Give every build a new folder.
    rm -rf "$SHARE/Cairn.app" "$SHARE"/build-* "$SHARE/vm.yaml" "$SHARE"/restore-*.txt "$SHARE"/restore-*.yaml "$SHARE"/wifi-*.txt "$SHARE"/wifi-test "$SHARE"/secrets-*.txt "$SHARE"/secrets-test "$SHARE"/install-*.txt "$SHARE"/install-test "$SHARE"/dock-status.txt "$SHARE"/auto-backup*.txt "$SHARE"/Test\ fake-install\ *.command
    BUILD_DIR="build-$(date +%Y%m%d-%H%M%S)"
    mkdir -p "$SHARE/$BUILD_DIR"
    cp -R dist/Cairn.app "$SHARE/$BUILD_DIR/"
    # Typing into a Tart window from outside is unreliable (keys get remapped),
    # so give the VM scripts it can run with a double-click in Finder. Each one
    # saves its output to the shared folder so the host can read it.
    runner() { # <name> <cairn arguments...>
        local file="$SHARE/$1.command" out="${1// /-}"; shift
        out="$(echo "$out" | tr '[:upper:]' '[:lower:]').txt"
        cat > "$file" <<EOF
#!/bin/sh
# Runs inside cairn-test. Generated by scripts/vm.sh stage.
D="/Volumes/My Shared Files/cairn"
cd "\$D" || exit 1
{ "\$D/$BUILD_DIR/Cairn.app/Contents/MacOS/cairn" $*; echo "exit: \$?"; } 2>&1 | tee "\$D/$out"
EOF
        chmod +x "$file"
        xattr -c "$file" 2>/dev/null || true
    }
    runner "Run Cairn scan" scan -o vm.yaml
    # Restore writes system state: these exist only in the VM's shared folder.
    runner "Restore preview" restore --from host.yaml
    runner "Restore apply" restore --from host.yaml --apply
    # Dock resume test helpers: fake an app install (an empty bundle the Dock
    # can show) to trigger the agent, then check what it did. Pick apps from the
    # backup's Dock that the VM lacks: FAKE_APPS="TickTick Obsidian" scripts/vm.sh stage
    for fake in ${FAKE_APPS:-TickTick Obsidian}; do
        cat > "$SHARE/Test fake-install $fake.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test only. Generated by scripts/vm.sh stage.
mkdir -p /Applications/$fake.app/Contents/MacOS
printf '<?xml version="1.0" encoding="UTF-8"?><plist version="1.0"><dict><key>CFBundleName</key><string>$fake</string><key>CFBundlePackageType</key><string>APPL</string></dict></plist>' > /Applications/$fake.app/Contents/Info.plist
echo "Created /Applications/$fake.app (fake). The agent adds it within 5 minutes; then run Dock status."
EOF2
    done
    cat > "$SHARE/Dock status.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test. Generated by scripts/vm.sh stage.
D="/Volumes/My Shared Files/cairn"
{
  echo "== cairn dock"; "\$D/$BUILD_DIR/Cairn.app/Contents/MacOS/cairn" dock
  echo "== Dock tiles"; defaults export com.apple.dock - | grep -o 'file:///[^<]*'
  echo "== agent"; ls ~/Library/LaunchAgents/dev.cairn.dock-resume.plist 2>&1; launchctl print gui/\$(id -u)/dev.cairn.dock-resume 2>&1 | grep -E 'state|runs|last exit' 
  echo "== agent log"; cat ~/Library/Logs/Cairn/dock-resume.log 2>&1
} 2>&1 | tee "\$D/dock-status.txt"
EOF2
    # Auto-backup test helpers. Snapshots go to vm-backups in the shared folder, so
    # the host can read them (and it stands in for a mounted NAS share).
    CAIRN_VM="\$D/$BUILD_DIR/Cairn.app/Contents/MacOS/cairn"
    cat > "$SHARE/Auto-backup on.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test only. Generated by scripts/vm.sh stage.
D="/Volumes/My Shared Files/cairn"
mkdir -p "\$D/vm-backups"
"$CAIRN_VM" auto-backup on --every 10 --to "\$D/vm-backups" 2>&1 | tee "\$D/auto-backup.txt"
EOF2
    cat > "$SHARE/Auto-backup status.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test. Generated by scripts/vm.sh stage.
D="/Volumes/My Shared Files/cairn"
{
  echo "== status"; "$CAIRN_VM" auto-backup status
  echo "== snapshots"; "$CAIRN_VM" snapshots --in "\$D/vm-backups"
  echo "== newest diff"; "$CAIRN_VM" snapshots --in "\$D/vm-backups" --diff
  echo "== agent"; launchctl print gui/\$(id -u)/dev.cairn.auto-backup 2>&1 | grep -E 'state|runs|last exit'
  echo "== log"; cat ~/Library/Logs/Cairn/auto-backup.log 2>&1
} 2>&1 | tee "\$D/auto-backup-status.txt"
EOF2
    cat > "$SHARE/Change Dock size.command" <<'EOF2'
#!/bin/sh
# Runs inside cairn-test only: changes a Dock setting so auto-backup has something to save.
size=$(( $(date +%s) % 40 + 30 ))
defaults write com.apple.dock tilesize -int $size && killall Dock
echo "Dock tile size is now $size at $(date). Auto-backup should notice within ~10 minutes."
EOF2
    chmod +x "$SHARE"/*.command
    xattr -c "$SHARE"/*.command 2>/dev/null || true
    echo "==> Scanning this Mac (read-only) → $SHARE/host.yaml"
    dist/Cairn.app/Contents/MacOS/cairn scan -o "$SHARE/host.yaml"
    # Restore test manifests (VM only): first force Light, then restore this Mac's
    # backup with a visibly different wallpaper, so the live Dark Mode switch and
    # the wallpaper change both show.
    sed 's/^  value: Dark$/  value: Light/' "$SHARE/host.yaml" > "$SHARE/restore-light.yaml"
    sed 's#path: /System/Library/CoreServices/DefaultDesktop.heic#path: /System/Library/Desktop Pictures/Mac Purple.heic#' \
        "$SHARE/host.yaml" > "$SHARE/restore-test.yaml"
    cat > "$SHARE/Restore test (light, then backup).command" <<EOF2
#!/bin/sh
# Runs inside cairn-test only: writes system state.
D="/Volumes/My Shared Files/cairn"
cd "\$D" || exit 1
{ "$CAIRN_VM" restore --from restore-light.yaml --apply; echo "== now the backup"; "$CAIRN_VM" restore --from restore-test.yaml --apply; echo "exit: \$?"; } 2>&1 | tee "\$D/restore-test.txt"
EOF2
    chmod +x "$SHARE"/*.command; xattr -c "$SHARE"/*.command 2>/dev/null || true
    # Wi-Fi restore test (VM only): a backup with one made-up network whose password
    # is in a test vault, and one without. The runner watches every process's
    # arguments while it restores, to prove the password never reaches a command line.
    CAIRN_VM_WIFI_FIXTURE="$SHARE/wifi-test" swift test --filter VMWiFiFixture >/dev/null
    # SSH key and share password restore test (VM only): two throwaway keys made
    # just now (one passphrase-protected), sealed into a test vault with a
    # made-up share password. The runner watches process arguments as above.
    KEYS="$(mktemp -d)"
    ssh-keygen -q -t ed25519 -N "" -C cairn-test -f "$KEYS/cairn_test_ed25519"
    ssh-keygen -q -t ed25519 -N "made-up-passphrase" -C cairn-test-locked -f "$KEYS/cairn_test_locked"
    # Milestone 5 install test (VM only): a tap, small formulae, a cask that needs
    # no sudo and one that does, an App Store app, a Dock tile for the cask, and a
    # made-up ~/.npmrc. Run it before and after installing Homebrew in the VM.
    CAIRN_VM_INSTALL_FIXTURE="$SHARE/install-test" swift test --filter VMInstallFixture >/dev/null
    cat > "$SHARE/Install restore test.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test only: installs packages and writes ~/.npmrc. Made-up token.
D="/Volumes/My Shared Files/cairn"
cd "\$D" || exit 1
out="\$D/install-restore-\$(date +%H%M%S).txt"
seen="\$D/install-argv.txt"; : > "\$seen"
( while :; do ps -axww -o args= | grep -c "made-up-npm-token-55" | grep -v '^1\$' >> "\$seen"; sleep 0.05; done ) &
watcher=\$!
{
  echo "== tools: \$(xcode-select -p 2>&1) | brew: \$(command -v brew || ls /opt/homebrew/bin/brew 2>&1)"
  echo "== restore"
  date
  echo vm-test-vault-pass | "$CAIRN_VM" restore --from install-test/manifest.yaml --apply --password-stdin
  echo "exit: \$?"; date
  echo "== ~/.npmrc"; ls -le ~/.npmrc 2>&1
  echo "== change ~/.npmrc, restore again: it must be left alone"
  [ -f ~/.npmrc ] && printf 'registry=https://example.invalid/\n' > ~/.npmrc
  echo vm-test-vault-pass | "$CAIRN_VM" restore --from install-test/manifest.yaml --apply --password-stdin 2>&1 | sed -n '/Still to do/,\$p'
  echo "== ~/.npmrc after"; ls -le ~/.npmrc 2>&1; head -c 40 ~/.npmrc 2>/dev/null; echo
  echo "== Dock"; defaults export com.apple.dock - | grep -o 'file:///[^<]*'
  echo "== cairn dock"; "$CAIRN_VM" dock
} 2>&1 | tee "\$out"
kill \$watcher
echo "== ps lines showing the token (other than the watcher's own grep): \$(wc -l < "\$seen" | tr -d ' ')" | tee -a "\$out"
EOF2
    CAIRN_VM_SECRETS_FIXTURE="$SHARE/secrets-test" CAIRN_VM_SSH_KEYS="$KEYS" swift test --filter VMSecretsFixture >/dev/null
    # A line of the unprotected key's body, to look for in process arguments.
    KEYLINE="$(sed -n 2p "$KEYS/cairn_test_ed25519" | cut -c1-40)"
    rm -rf "$KEYS"
    cat > "$SHARE/Secrets restore test.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test only: writes ~/.ssh and the login keychain. Throwaway keys, made-up password.
D="/Volumes/My Shared Files/cairn"
cd "\$D" || exit 1
seen="\$D/secrets-argv.txt"; : > "\$seen"
( while :; do ps -axww -o args= | grep -c -e "made-up-share-pass-77" -e "$KEYLINE" | grep -v '^1\$' >> "\$seen"; sleep 0.05; done ) &
watcher=\$!
{
  echo vm-test-vault-pass | "$CAIRN_VM" restore --from secrets-test/manifest.yaml --apply --password-stdin
  echo "exit: \$?"
  echo "== ~/.ssh"; ls -le ~/.ssh | grep -v '^total'; stat -f '%Sp %N' ~/.ssh
  echo "== public key"; cat ~/.ssh/cairn_test_ed25519.pub 2>&1
  echo "== share password item"
  security find-internet-password -s nas.example -a cairntest 2>&1 | grep -E 'keychain:|"acct"|"srvr"|"ptcl"|"labl"|could not'
} 2>&1 | tee "\$D/secrets-restore.txt"
kill \$watcher
echo "== ps lines showing a secret (other than the watcher's own grep): \$(wc -l < "\$seen" | tr -d ' ')" | tee -a "\$D/secrets-restore.txt"
EOF2
    chmod +x "$SHARE"/*.command; xattr -c "$SHARE"/*.command 2>/dev/null || true
    cat > "$SHARE/Wi-Fi restore test.command" <<EOF2
#!/bin/sh
# Runs inside cairn-test only: writes the Keychain. Made-up networks and passwords.
D="/Volumes/My Shared Files/cairn"
cd "\$D" || exit 1
seen="\$D/wifi-argv.txt"; : > "\$seen"
( while :; do ps -axww -o args= | grep -c "made-up-wifi-pass-42" | grep -v '^1\$' >> "\$seen"; sleep 0.05; done ) &
watcher=\$!
{
  echo vm-test-vault-pass | "$CAIRN_VM" restore --from wifi-test/manifest.yaml --apply --password-stdin
  echo "exit: \$?"
  for kc in ~/Library/Keychains/login.keychain-db /Library/Keychains/System.keychain; do
    echo "== Cairn-Test-Cafe in \$kc"
    security find-generic-password -D "AirPort network password" -a Cairn-Test-Cafe "\$kc" 2>&1 | grep -E 'keychain:|"acct"|"svce"|"desc"|could not'
  done
} 2>&1 | tee "\$D/wifi-restore.txt"
kill \$watcher
echo "== ps lines showing the password (other than the watcher's own grep): \$(wc -l < "\$seen" | tr -d ' ')" | tee -a "\$D/wifi-restore.txt"
EOF2
    chmod +x "$SHARE"/*.command; xattr -c "$SHARE"/*.command 2>/dev/null || true
    ;;
run)
    need_tart
    vm_exists "$TEST" || { echo "No $TEST yet. Run: scripts/vm.sh fresh" >&2; exit 1; }
    mkdir -p "$SHARE"
    tart run "$TEST" --dir "cairn:$SHARE"
    ;;
compare)
    for f in host.yaml vm.yaml; do
        [ -f "$SHARE/$f" ] || { echo "Missing $SHARE/$f" >&2; exit 1; }
    done
    dist/Cairn.app/Contents/MacOS/cairn diff "$SHARE/host.yaml" "$SHARE/vm.yaml" || true
    ;;
*)
    sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
